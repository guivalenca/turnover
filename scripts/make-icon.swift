// Regenerates Turnover's icon artwork from the ring of the chosen design ("A, the ring" in blue:
// prototypes/icon-a-prototype.html on the prototype/ring branch).
//
//   swift scripts/make-icon.swift                      rewrite the SVG shapes listed below
//   swift scripts/make-icon.swift --previews <folder>  also render PNG previews of every appearance
//
// It owns only the shapes:
//   App/AppIcon.icon/Assets/lit.svg, bottom.svg, left.svg  the three ring segments, top right lit
//   App/AppIcon.icon/Assets/glow.svg                       the soft light in the top-left corner
//   App/Assets.xcassets/MenuBarGlyph.imageset/MenuBarGlyph.svg  the menu bar template glyph
// Colours, glass, shadows and the dark appearance are in App/AppIcon.icon/icon.json, which
// Icon Composer (in Xcode) opens and edits; macOS derives the tinted and clear appearances.
// Xcode compiles the .icon into the app's Assets.car for macOS 26 and later, plus AppIcon.icns
// for macOS 15.
//
// Previews need Xcode's Icon Composer, whose ictool renders an .icon the way macOS does.

import AppKit
import Foundation

let root = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
let iconFolder = root.appending(path: "App/AppIcon.icon")
let glyphFolder = root.appending(path: "App/Assets.xcassets/MenuBarGlyph.imageset")

// MARK: Geometry

/// An annular sector with rounded corners: the sector between `inner` and `outer` from angle
/// `start` to `end` (degrees, clockwise from 3 o'clock, as in SVG), grown by `rounding` on every
/// side with round corners. That is the shape the prototype draws as a sector stroked with
/// round joins, so the segments read as soft glass pieces rather than sharp cuts.
struct Segment {
    var inner: Double, outer: Double, start: Double, end: Double, rounding: Double

    func path(center c: Double) -> String {
        let d = rounding
        func point(_ r: Double, _ degrees: Double, nudge: Double = 0, toward normal: Double = 0) -> String {
            let a = degrees * .pi / 180, n = normal * .pi / 180
            return "\(f(c + r * cos(a) + nudge * cos(n))) \(f(c + r * sin(a) + nudge * sin(n)))"
        }
        let after = end + 90, before = start - 90  // outward normals of the two straight edges
        return [
            "M\(point(outer + d, start))",
            "A\(f(outer + d)) \(f(outer + d)) 0 0 1 \(point(outer + d, end))",
            "A\(f(d)) \(f(d)) 0 0 1 \(point(outer, end, nudge: d, toward: after))",
            "L\(point(inner, end, nudge: d, toward: after))",
            "A\(f(d)) \(f(d)) 0 0 1 \(point(inner - d, end))",
            "A\(f(inner - d)) \(f(inner - d)) 0 0 0 \(point(inner - d, start))",
            "A\(f(d)) \(f(d)) 0 0 1 \(point(inner, start, nudge: d, toward: before))",
            "L\(point(outer, start, nudge: d, toward: before))",
            "A\(f(d)) \(f(d)) 0 0 1 \(point(outer + d, start))",
            "Z",
        ].joined()
    }
}

func f(_ x: Double) -> String {
    var s = String(format: "%.2f", x)
    while s.hasSuffix("0") { s.removeLast() }
    if s.hasSuffix(".") { s.removeLast() }
    return s == "-0" ? "0" : s
}

func svg(size: Double, _ body: String) -> String {
    """
    <?xml version="1.0" encoding="UTF-8"?>
    <!-- Generated by scripts/make-icon.swift; edit that script, not this file. -->
    <svg xmlns="http://www.w3.org/2000/svg" width="\(f(size))" height="\(f(size))" viewBox="0 0 \(f(size)) \(f(size))">
    \(body)
    </svg>

    """
}

// The app icon. The prototype draws the squircle 824 wide in a 1024 box; an .icon's 1024-point
// canvas is the squircle itself, so every length is scaled by 1024 / 824.
let scale = 512.0 / 412
let ring = (inner: 158 * scale, outer: 262 * scale, rounding: 12 * scale)
func iconSegment(_ start: Double, _ end: Double) -> Segment {
    Segment(inner: ring.inner, outer: ring.outer, start: start, end: end, rounding: ring.rounding)
}
// One layer per segment, so that each gets its own top-left to bottom-right glass gradient.
let segments = [("lit", iconSegment(-110, -10)), ("bottom", iconSegment(10, 110)), ("left", iconSegment(130, 230))]

// The menu bar glyph: the prototype's 16-point glyph, the lit segment solid and the other two
// at 35% (a template image keeps its alpha). Its corners are rounded by half a point, inside
// the prototype's outline.
let glyphRounding = 0.5
func glyphSegment(_ start: Double, _ end: Double) -> Segment {
    let inner = 3.2 + glyphRounding, outer = 6.6 - glyphRounding
    let trim = glyphRounding / ((inner + outer) / 2) * 180 / .pi
    return Segment(inner: inner, outer: outer, start: start + trim, end: end - trim, rounding: glyphRounding)
}

// MARK: Writing

func write(_ text: String, to url: URL) throws {
    try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
    try text.write(to: url, atomically: true, encoding: .utf8)
    print("wrote \(url.path(percentEncoded: false).replacingOccurrences(of: root.path(percentEncoded: false), with: ""))")
}

func shape(_ segments: [Segment], center: Double, color: String, opacity: Double = 1) -> String {
    let alpha = opacity < 1 ? " fill-opacity=\"\(f(opacity))\"" : ""
    return "<path fill=\"\(color)\"\(alpha) d=\"\(segments.map { $0.path(center: center) }.joined())\"/>"
}

// Segment shapes are plain white: icon.json gives each layer its fill per appearance.
for (name, segment) in segments {
    try write(svg(size: 1024, shape([segment], center: 512, color: "#FFFFFF")),
              to: iconFolder.appending(path: "Assets/\(name).svg"))
}
// The prototype's radial light (centre at 30% across and 8% down, radius 80%), at full
// strength; icon.json sets its opacity per appearance.
try write(svg(size: 1024, """
    <defs><radialGradient id="glow" cx="\(f(0.3 * 1024))" cy="\(f(0.08 * 1024))" r="\(f(0.8 * 1024))" gradientUnits="userSpaceOnUse">
    <stop offset="0" stop-color="#FFFFFF"/><stop offset="1" stop-color="#FFFFFF" stop-opacity="0"/></radialGradient></defs>
    <rect width="1024" height="1024" fill="url(#glow)"/>
    """), to: iconFolder.appending(path: "Assets/glow.svg"))
try write(svg(size: 16, [
    shape([glyphSegment(-104, -16)], center: 8, color: "#000000"),
    shape([glyphSegment(16, 104), glyphSegment(136, 224)], center: 8, color: "#000000", opacity: 0.35),
].joined(separator: "\n")), to: glyphFolder.appending(path: "MenuBarGlyph.svg"))

// MARK: Previews

let arguments = CommandLine.arguments.dropFirst()
guard let flag = arguments.firstIndex(of: "--previews") else { exit(0) }
guard arguments.indices.contains(flag + 1) else {
    FileHandle.standardError.write(Data("usage: swift scripts/make-icon.swift [--previews <folder>]\n".utf8))
    exit(64)
}
let previews = URL(fileURLWithPath: arguments[flag + 1], isDirectory: true)
try FileManager.default.createDirectory(at: previews, withIntermediateDirectories: true)

let developer = try {
    let p = Process()
    p.executableURL = URL(fileURLWithPath: "/usr/bin/xcode-select")
    p.arguments = ["-p"]
    let out = Pipe()
    p.standardOutput = out
    try p.run()
    p.waitUntilExit()
    return String(decoding: out.fileHandleForReading.readDataToEndOfFile(), as: UTF8.self)
        .trimmingCharacters(in: .whitespacesAndNewlines)
}()
let ictool = URL(fileURLWithPath: developer)
    .appending(path: "../Applications/Icon Composer.app/Contents/Executables/ictool").standardized

/// Renders the .icon with ictool as macOS draws it in one appearance ("rendition").
func renderIcon(_ rendition: String, points: Int, scale: Int = 2, generation: Int? = nil) throws -> NSImage {
    let file = previews.appending(path: "icon-\(rendition)-\(points)pt@\(scale)x\(generation.map { "-gen\($0)" } ?? "").png")
    let p = Process()
    p.executableURL = ictool
    p.arguments = [iconFolder.path, "--export-image", "--output-file", file.path, "--platform", "macOS",
                   "--rendition", rendition, "--width", "\(points)", "--height", "\(points)", "--scale", "\(scale)"]
        + (generation.map { ["--design-generation", "\($0)"] } ?? [])
    p.standardOutput = FileHandle.nullDevice
    try p.run()
    p.waitUntilExit()
    guard p.terminationStatus == 0, let image = NSImage(contentsOf: file) else {
        throw CocoaError(.fileReadCorruptFile, userInfo: [NSFilePathErrorKey: file.path])
    }
    return image
}

/// A contact sheet: each appearance large and at Finder and Dock sizes on a fitting wallpaper,
/// then the glyph in light and dark menu bars.
func sheet(generation: Int?) throws -> NSImage {
    let renditions: [(name: String, label: String, wallpaper: [NSColor])] = [
        ("Default", "Default", [NSColor(srgbRed: 0.87, green: 0.91, blue: 0.97, alpha: 1), NSColor(srgbRed: 0.95, green: 0.90, blue: 0.93, alpha: 1)]),
        ("Dark", "Dark", [NSColor(srgbRed: 0.08, green: 0.10, blue: 0.20, alpha: 1), NSColor(srgbRed: 0.16, green: 0.09, blue: 0.19, alpha: 1)]),
        ("TintedLight", "Tinted (light)", [NSColor(srgbRed: 0.80, green: 0.82, blue: 0.86, alpha: 1), NSColor(srgbRed: 0.70, green: 0.72, blue: 0.77, alpha: 1)]),
        ("TintedDark", "Tinted (dark)", [NSColor(srgbRed: 0.17, green: 0.18, blue: 0.23, alpha: 1), NSColor(srgbRed: 0.11, green: 0.11, blue: 0.14, alpha: 1)]),
        ("ClearLight", "Clear (light)", [NSColor(srgbRed: 0.56, green: 0.72, blue: 0.94, alpha: 1), NSColor(srgbRed: 0.91, green: 0.65, blue: 0.77, alpha: 1)]),
        ("ClearDark", "Clear (dark)", [NSColor(srgbRed: 0.16, green: 0.25, blue: 0.47, alpha: 1), NSColor(srgbRed: 0.35, green: 0.16, blue: 0.31, alpha: 1)]),
    ]
    let cell = 300.0, big = 220.0, smalls = [64, 32, 16], gap = 16.0, label = 22.0
    let cardHeight = 24 + big + 24 + 64 + 24
    let width = gap + Double(renditions.count) * (cell + gap)
    let height = gap + label + cardHeight + gap + 64 + gap
    let image = NSImage(size: NSSize(width: width, height: height))
    image.lockFocusFlipped(true)
    NSColor(srgbRed: 0.96, green: 0.96, blue: 0.97, alpha: 1).setFill()
    NSRect(x: 0, y: 0, width: width, height: height).fill()
    let text: [NSAttributedString.Key: Any] = [.font: NSFont.systemFont(ofSize: 13, weight: .medium), .foregroundColor: NSColor.darkGray]
    for (i, r) in renditions.enumerated() {
        let x = gap + Double(i) * (cell + gap)
        (r.label + (generation.map { " · gen \($0)" } ?? "")).draw(at: NSPoint(x: x + 4, y: gap), withAttributes: text)
        let card = NSRect(x: x, y: gap + label, width: cell, height: cardHeight)
        NSGradient(colors: r.wallpaper)!.draw(in: NSBezierPath(roundedRect: card, xRadius: 14, yRadius: 14), angle: -70)
        try renderIcon(r.name, points: 1024, scale: 1, generation: generation)
            .draw(in: NSRect(x: x + (cell - big) / 2, y: card.minY + 24, width: big, height: big))
        var sx = x + 40.0
        for points in smalls {
            let s = Double(points)
            try renderIcon(r.name, points: points, generation: generation)
                .draw(in: NSRect(x: sx, y: card.maxY - 24 - s, width: s, height: s))
            sx += s + 36
        }
    }
    // The menu bar glyph as AppKit draws a template image (black in a light menu bar, white in a
    // dark one, keeping its alpha): at its real 16 points beside a percentage, then 4× larger.
    let glyph = NSImage(contentsOf: glyphFolder.appending(path: "MenuBarGlyph.svg"))!
    let barY = gap + label + cardHeight + gap
    for (i, dark) in [false, true].enumerated() {
        let ink = dark ? NSColor.white : NSColor.black
        let tinted = NSImage(size: glyph.size, flipped: false) { rect in
            glyph.draw(in: rect)
            ink.set()
            rect.fill(using: .sourceAtop)
            return true
        }
        let x = gap + Double(i) * (cell + gap)
        let bar = NSRect(x: x, y: barY + 20, width: 110, height: 24)
        let panel = NSRect(x: x, y: barY, width: cell, height: 64)
        (dark ? NSColor(white: 0.15, alpha: 1) : NSColor.white).setFill()
        NSBezierPath(roundedRect: panel, xRadius: 10, yRadius: 10).fill()
        tinted.draw(in: NSRect(x: bar.minX + 14, y: bar.minY + 4, width: 16, height: 16))
        "62%".draw(at: NSPoint(x: bar.minX + 36, y: bar.minY + 3),
                   withAttributes: [.font: NSFont.monospacedDigitSystemFont(ofSize: 13, weight: .regular), .foregroundColor: ink])
        tinted.draw(in: NSRect(x: x + cell - 64 - 16, y: barY, width: 64, height: 64))
    }
    image.unlockFocus()
    return image
}

func savePNG(_ image: NSImage, _ name: String) throws {
    let rep = NSBitmapImageRep(data: image.tiffRepresentation!)!
    let url = previews.appending(path: name)
    try rep.representation(using: .png, properties: [:])!.write(to: url)
    print("wrote \(url.path)")
}

// macOS 26 draws icons with the design generation 26 look and macOS 27 with 27, from the same
// compiled .icon, so check both when this Xcode's ictool can draw both (Xcode 27 and later).
func ictoolHelp() throws -> String {
    let p = Process()
    p.executableURL = ictool
    p.arguments = ["--help"]
    let out = Pipe()
    p.standardOutput = out
    p.standardError = out
    try p.run()
    let text = String(decoding: out.fileHandleForReading.readDataToEndOfFile(), as: UTF8.self)
    p.waitUntilExit()
    return text
}
if try ictoolHelp().contains("--design-generation") {
    for generation in [26, 27] {
        try savePNG(try sheet(generation: generation), "sheet-gen\(generation).png")
    }
} else {
    try savePNG(try sheet(generation: nil), "sheet.png")
}
